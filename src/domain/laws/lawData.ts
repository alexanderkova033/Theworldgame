type LawSpec = Omit<LawNode, "quota" | "enactCost"> & { resource?: [ResourceType, number] };

function law({ resource, ...node }: LawSpec): LawNode {
  const enactCost: LawEnactCost = { treasury: LAW_PRICE_BY_TIER[node.tier], politicalPower: LAW_POLITICAL_POWER_BY_TIER[node.tier] };
  if (resource) {
    enactCost.resourceType = resource[0];
    enactCost.resourceAmount = resource[1];
  }
  return { ...node, quota: QUOTAS[node.category][node.tier], enactCost };
}

