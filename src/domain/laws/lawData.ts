// Four branches of seven rows. Each grows from one shared law (row 1) into
// three paths that never cross, each in its own lane on the tree and with
// its own name. The first law of a path closes the other two paths for
// good, since only one law per row of a branch can pass (see
// domain/policy/treeRules.ts). Inside a path, rows 4 and 5 fork in two and
// meet again at row 6; row 7 is the path's capstone. Some laws also close
// off a law in another branch or a technology (`excludes`).
//
// Each branch also has a capstone only one kind of party would ever put to
// a vote (`ideology`), in the lane that suits it: you see it only if your
// party is of that ideology, and it competes with that lane's own capstone.
//
// What a law does is its `effects`; the benefit and cost lines shown in the
// game are written from those numbers (see describeEffects), so they can't
// drift apart. Its quota and price come from its branch and row.

