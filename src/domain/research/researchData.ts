// Four areas of seven rows, shaped like the Law branches: one shared
// technology at the root, then three paths that never cross, each in its
// own lane. Only one technology per row of an area can be developed (see
// domain/policy/treeRules.ts), so a path's first technology closes the
// other two for good. Rows 4 and 5 fork each path in two, and they meet
// again at row 6; row 7 is the path's capstone. A few also close off a law,
// or are closed off by one (`excludes`, which works both ways).
//
// No quota and no vote: an area just works toward the node you point it
// at, at a pace set by its buildings and scientists (see researchRules.ts);
// a node costs RESEARCH_COST_BY_TIER points of that work. How well it turns
// out is rolled when it's done (see researchOutcomes.ts).
//
// The benefit and cost lines shown in the game are written from `effects`
// (see describeEffects), so they can't drift apart.

