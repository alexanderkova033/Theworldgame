// The game rolls dice (events, votes, research outcomes) with Math.random.
// Tests swap in a seeded generator (mulberry32) so every run plays out the
// same way and a pass or a failure can be repeated.
export function seedRandom(seed: number): void {
  let a = seed >>> 0;
  Math.random = () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
